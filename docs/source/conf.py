#
# Typesetting conventions:
#   - Scalars are in normal font.
#   - Tensors (rank >= 1) are bold. Their elements are scalars and are in
#     normal font.
#   - Operators have hats. Tensor operators are also bold.
#   - Anything that depends on the nuclear coordinates or momenta is an
#     operator.
#
# Naming conventions: ``*vec`` macros are bold tensors (with a hat if they are
# operators) and ``*op`` macros are scalar operators, including the elements
# of tensor operators.
